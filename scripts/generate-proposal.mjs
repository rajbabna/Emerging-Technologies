import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  writeFileSync,
} from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const scriptDir = dirname(fileURLToPath(import.meta.url));
const webRoot = join(scriptDir, "..");

// Prefer the live proposal in the full lms tree, then fall back to the
// vendored copy so the standalone `web` repository can deploy on its own.
const lmsSource = join(webRoot, "..", "project", "PROJECT-PROPOSAL.md");
const localCopy = join(webRoot, "content", "project-proposal.md");
const target = join(webRoot, "src", "lib", "project-proposal.generated.ts");

if (existsSync(lmsSource)) {
  mkdirSync(dirname(localCopy), { recursive: true });
  copyFileSync(lmsSource, localCopy);
  console.log(`[generate-proposal] Synced ${localCopy}`);
}

function rewriteLinks(markdown) {
  const base = process.env.NEXT_PUBLIC_BASE_PATH ?? "";
  const routes = {
    "../LMS-PROPOSAL.md": "/",
    "../syllabus/C25-architecture-os.md": "/c25",
    "../syllabus/C26-cloud-computing.md": "/c26",
    "../syllabus/C27-iot-ai.md": "/c27",
    "../implementation/ROADMAP.md": "/dashboard",
  };

  return markdown.replace(
    /\[([^\]]+)\]\((\.\.\/[^)]+|\.\/_archive\/[^)]+)\)/g,
    (match, text, href) => {
      if (routes[href]) return `[${text}](${base}${routes[href]})`;
      if (href.startsWith("./_archive/")) return text;
      return match;
    },
  );
}

let markdown = "# Project proposal\n\nThe proposal file could not be loaded.";

try {
  const raw = readFileSync(localCopy, "utf8");
  markdown = rewriteLinks(raw.replace(/^---[\s\S]*?---\s*/, ""));
} catch (error) {
  console.warn(`[generate-proposal] Could not read ${localCopy}: ${error.message}`);
}

const output = `// AUTO-GENERATED by scripts/generate-proposal.mjs\n// Source: content/project-proposal.md\nexport const projectProposalMarkdown = ${JSON.stringify(
  markdown,
)};\n`;

writeFileSync(target, output, "utf8");
console.log(`[generate-proposal] Wrote ${target}`);
